"""Bake the generated smoke height map to a small, synchronous runtime grid.

Run with Pillow installed: python tools/bake-smoke-noise.py
The PNG remains the editable source; browsers need no image decode or GPU texture.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
image = Image.open(root / 'assets/pnt/vfx/hammer-smoke-noise.png').convert('L')
grid = image.resize((64, 64), Image.Resampling.LANCZOS)
values = list(grid.tobytes())
rows = [','.join(map(str, values[i:i+64])) for i in range(0, len(values), 64)]
output = '// Generated by tools/bake-smoke-noise.py from assets/pnt/vfx/hammer-smoke-noise.png.\n'
output += 'export const smokeNoiseSize=64;\nexport const smokeNoiseHeights=new Uint8Array([\n'
output += ',\n'.join(rows) + '\n]);\n'
(root / 'src/pnt/smoke-noise-data.js').write_text(output, encoding='utf-8')

